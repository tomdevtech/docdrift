"""Installation into a target repository: config, pre-push hook, GitHub workflows.

Used by ``docdrift init``, ``docdrift init-github-obsidian`` and
``docdrift init-github-product``. Every file is written with LF line endings -
a shell hook saved with Windows line endings does not even start.
"""

from __future__ import annotations

import importlib.resources
import stat
import sys
from pathlib import Path

from docdrift.core.config import CONFIG_RELATIVE_PATH

#: Entries that keep machine-local data out of version control.
GITIGNORE_ENTRIES = (".docdrift/state/", ".docdrift/logs/")


# Written by `docdrift init`. Doubled braces escape ${...} for str.format().
DEFAULT_CONFIG_TEMPLATE = """\
# Generated by `docdrift init` - see the README for all options.
repo_name: "{repo_name}"

api_base_url: "http://localhost:11434/v1"
model: "qwen2.5-coder:14b"

# Upper bound for one LLM prompt in characters (~4 chars per token). Keep it
# well below the context length configured in Ollama / LM Studio.
max_prompt_chars: 12000

language: "English"               # language of the notes in the vault, e.g. "German"

obsidian:
  access_mode: "local"
  vault_path: "~/ObsidianVault"   # the vault root (or its Projects folder); notes go to <vault>/Projects/<repo>/
  rest_api_base_url: ""
  rest_api_key: "${{OBSIDIAN_REST_API_KEY}}"

mode: "both"                      # both | overview (only the HLA note _Architecture.md) | per-file

adr:
  enabled: true
  threshold: 4                    # minimum significance score; ADRs go to the vault only

github_docs:                      # merge flow (product docs only), see `docdrift init-github-product`
  enabled: true                   # after a merge: check and update README / docs_paths
  precheck: true                  # skip merges that cannot affect users (saves requests)
  engine: "copilot"               # copilot (needs a Copilot licence) | github-models (free, rate-limited)
  assignee: "copilot"
  docs_paths:
    - "docs/"
    - "README.md"

ignore:
  - "tests/"
  - "docs/"
  - "*.md"
  - "*.lock"
  - ".github/"
  - ".docdrift/*"
"""


def install_config(project_root: Path) -> Path:
    """Write the default config during ``docdrift init`` (idempotent)."""
    config_path = project_root / CONFIG_RELATIVE_PATH
    config_path.parent.mkdir(parents=True, exist_ok=True)
    if config_path.exists():
        return config_path
    config_path.write_text(
        DEFAULT_CONFIG_TEMPLATE.format(repo_name=project_root.name), encoding="utf-8"
    )
    return config_path


def template(package: str, *parts: str) -> str:
    """Read a bundled template, e.g. ``template("local", "hooks", "pre-push.template")``."""
    return (
        importlib.resources.files(f"docdrift.{package}").joinpath(*parts).read_text(encoding="utf-8")
    )


def write_lf(path: Path, text: str) -> None:
    """Write with LF line endings on every OS - a CRLF shell hook does not even start."""
    path.write_text(text, encoding="utf-8", newline="\n")


def hook_script() -> str:
    """The pre-push hook, pointing at the interpreter docdrift is installed in.

    Hooks also run from IDEs and Git GUIs where the virtualenv is not activated,
    so the absolute interpreter path is more reliable than ``docdrift`` on PATH.
    """
    python = Path(sys.executable).as_posix()  # forward slashes work in Git Bash too
    for ch in ('\\', '"', "$", "`"):
        python = python.replace(ch, "\\" + ch)
    return template("local", "hooks", "pre-push.template").replace("__PYTHON__", python)


def ensure_gitignore_entry(repo_root: Path, entry: str) -> None:
    """Add ``entry`` to ``.gitignore`` unless it is already there.

    Keeps the machine-local state (last documented commit) out of version control.
    """
    path = repo_root / ".gitignore"
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    if entry in existing.splitlines():
        return
    separator = "\n" if existing and not existing.endswith("\n") else ""
    with path.open("a", encoding="utf-8") as f:
        f.write(f"{separator}{entry}\n")


def install_workflow(repo_root: Path, package: str, name: str) -> Path:
    """Copy ``docdrift/<package>/github_workflows/<name>.yml.template`` to ``.github/workflows/``."""
    target_dir = repo_root / ".github" / "workflows"
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / f"{name}.yml"
    write_lf(target, template(package, "github_workflows", f"{name}.yml.template"))
    return target


def install_hook(repo_root: Path) -> tuple[Path, Path | None]:
    """Install the pre-push hook; a foreign hook is kept as ``pre-push.bak``.

    Returns ``(hook, backup or None)``.
    """
    hook = repo_root / ".git" / "hooks" / "pre-push"
    hook.parent.mkdir(parents=True, exist_ok=True)
    backup = None
    if hook.exists() and "docdrift" not in hook.read_text(encoding="utf-8", errors="replace"):
        backup = hook.with_name("pre-push.bak")
        hook.replace(backup)
    write_lf(hook, hook_script())
    hook.chmod(hook.stat().st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
    return hook, backup


def install_local(repo_root: Path) -> tuple[Path, Path, Path | None]:
    """Everything ``docdrift init`` does: config, hook, state folder, .gitignore.

    Returns ``(config, hook, backup of a foreign hook or None)``.
    """
    config = install_config(repo_root)
    hook, backup = install_hook(repo_root)
    (repo_root / ".docdrift" / "state").mkdir(parents=True, exist_ok=True)
    for entry in GITIGNORE_ENTRIES:
        ensure_gitignore_entry(repo_root, entry)
    return config, hook, backup
